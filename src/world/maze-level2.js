function rebuildLevelFromMap(buildOptions = {}) {
    if (window.levelUtils) {
        const inspection = window.levelUtils.inspect(window.levelMap);
        if (!inspection.valid) throw new Error(inspection.errors.join(" "));
        window.levelMap = inspection.map;
    }

    const levelOptions = {
        cellSize: LEVEL_CELL_SIZE,
        wallHeight: LEVEL_CELL_SIZE * 3,
        wallDepth: 0.5,
        wallColor: 0x8b5a2b,
        ...buildOptions,
    };
    if (typeof NARRATIVE !== "undefined") levelOptions.narrative = NARRATIVE;

    const spawn = buildMazeFromAsciiMap(window.levelMap, levelOptions);
    if (spawn) {
        window.spawnPoint = spawn;
        camera.position.set(spawn.x, spawn.y, spawn.z);
    }
    return spawn;
}

window.rebuildLevelFromMap = rebuildLevelFromMap;
rebuildLevelFromMap();

if (typeof window.setNightMode === "function") {
    window.setNightMode(true);
    if (window.spawnPoint && typeof window.updateRenderVisibility === "function") {
        window.updateRenderVisibility(window.spawnPoint.x, window.spawnPoint.z);
    }
    renderer.compile(scene, camera);
}
